/**
 * Readable summaries of a company build, for the human reviewer:
 *
 *   <company>/research-summary.md   counts, what becomes a page and what doesn't, review items
 *   <company>/<role>/README.md      one role: sequences, rounds, every question with its
 *                                   independent reports and review flags — exactly what the
 *                                   role's page will import, readable in an editor
 *
 * Everything here is computed from the evidence; the judgement lives in the
 * company README the researcher writes and in the notes inside evidence.json.
 */
import { DEFAULT_INTERVIEW_CATEGORIES } from "./guide";
import type { BuiltRole, CompanyBuild } from "./research";

const label = new Map(DEFAULT_INTERVIEW_CATEGORIES.map((c) => [c.value, c.label]));
const plural = (n: number, one: string, many = `${one}s`) => `${n} ${n === 1 ? one : many}`;
const cell = (value: string) => value.replace(/\|/g, "\\|").replace(/\s+/g, " ").trim();
const table = (head: string[], rows: string[][]) => [`| ${head.join(" | ")} |`, `| ${head.map(() => "---").join(" | ")} |`, ...rows.map((r) => `| ${r.map(cell).join(" | ")} |`)].join("\n");

export function renderRoleReadme(build: CompanyBuild, role: BuiltRole): string {
  const page = role.page;
  const out: string[] = [
    `# ${build.company} ${role.role} Interview Experiences`,
    "",
    `> Generated by \`npm run interviews:build\` from evidence.json; edit the evidence, not this file. Candidate-reported: not ${build.company}'s official process, and not complete.`,
    "",
    `- Independent candidate accounts: **${role.accounts}**${role.period ? ` (${role.period})` : ""}`,
    `- Rounds on the page: **${role.rounds.length}**; explicit questions: **${role.questions}** from ${plural(role.mentions, "mention")} (${role.review} need review)`,
    page ? `- Page: \`${page.slug}\` · advice **${page.advice.indexing}**: ${page.advice.reason}` : `- **No page**: ${role.reason}`,
    "",
    "## Reported sequences",
    "",
  ];
  out.push(role.sequences.length ? table(["Sequence (normalised round names)", "Accounts"], role.sequences.map((s) => [s.steps.join(" → "), String(s.reports)])) : "None recorded.");
  out.push("", "## Rounds", "");
  out.push(
    role.rounds.length
      ? table(
          ["Round", "Typical position", "Accounts", "Questions", "Need review", "Vague items (not imported)"],
          role.rounds.map((r) => [r.name, String(r.order), `${r.reports} of ${role.accounts}`, String(r.questions.length), String(r.questions.filter((q) => q.review).length), String(r.vague)]),
        )
      : "None.",
  );
  if (role.skipped.length) {
    out.push("", "Left out of the page:", "", table(["Round", "Accounts", "Why"], role.skipped.map((s) => [s.round, String(s.accounts), s.reason])));
  }
  if (role.notes.highlights.length) out.push("", "## Highlights (shown on the page)", "", ...role.notes.highlights.map((h) => `- ${h}`));
  if (role.notes.preparation.length) out.push("", "## Preparation candidates name (shown on the page)", "", ...role.notes.preparation.map((h) => `- ${h}`));

  for (const round of role.rounds) {
    out.push("", `## ${round.name}`, "", `Reported by ${round.reports} of ${role.accounts} accounts.`, "");
    out.push(round.summary ? `> ${round.summary.replace(/\n+/g, "\n> ")}` : "> _No summary yet (roleNotes.rounds)._");
    if (round.questions.length) {
      out.push("");
      round.questions.forEach((q, i) => {
        const tags = [label.get(q.category) ?? q.category, q.reports >= 2 ? `${q.reports} accounts` : null, q.difficulty, q.practiceUrl ? `practice: ${q.practiceUrl}` : null].filter(Boolean).join(" · ");
        out.push(`${i + 1}. ${q.review ? "**[NEEDS REVIEW]** " : ""}${q.text} — _${tags}_ \`${q.id}\`${q.review && q.reviewNote ? `\n   - Review: ${q.reviewNote}` : ""}`);
      });
    } else out.push("", "No explicit questions reported.");
  }
  if (role.notes.caveats.length) out.push("", "## Caveats (research only)", "", ...role.notes.caveats.map((c) => `- ${c}`));
  const reviewItems = [
    ...role.rounds.flatMap((r) => r.questions.filter((q) => q.review).map((q) => `${r.name} · \`${q.id}\`: ${q.text}${q.reviewNote ? ` (${q.reviewNote})` : ""}`)),
    ...role.notes.review,
  ];
  out.push("", "## Human review items", "", ...(reviewItems.length ? reviewItems.map((r) => `- ${r}`) : ["- None flagged. Still read each round before publishing."]));
  return `${out.join("\n")}\n`;
}

export function renderSummary(build: CompanyBuild): string {
  const ev = build.evidence;
  const kinds = new Map<string, number>();
  for (const s of ev.sources) kinds.set(s.kind, (kinds.get(s.kind) ?? 0) + 1);
  const groups = new Set(ev.experiences.map((e) => ev.sources.find((s) => s.id === e.source)!.independenceGroup));
  const copies = ev.experiences.reduce((n, e) => n + e.alsoOn.length, 0);
  const included = build.roles.filter((r) => r.page);
  const out: string[] = [
    `# ${build.company}: research summary (generated)`,
    "",
    `Run \`${build.researchRun}\`. Generated by \`npm run interviews:build\` from evidence.json; do not edit by hand.`,
    "",
    `- Sources recorded: ${ev.sources.length} (${[...kinds].map(([k, n]) => `${k} ${n}`).join(", ")})`,
    `- Candidate experiences: ${ev.experiences.length}, from ${groups.size} independent accounts; ${plural(copies, "syndicated copy", "syndicated copies")} not counted again`,
    `- Roles found: ${build.roles.length} · pages in import.json: ${build.pkg ? build.pkg.pages.length : 0} (the company page + ${plural(included.length, "role")})`,
    `- Excluded items logged: ${ev.excluded.length}`,
    "",
    "## Roles",
    "",
    table(
      ["Role", "Accounts", "Rounds", "Questions", "Need review", "Page", "Advice"],
      build.roles.map((r) => [r.role, String(r.accounts), String(r.rounds.length), String(r.questions), String(r.review), r.page ? r.page.slug : "none", r.page ? r.page.advice.indexing : r.reason]),
    ),
  ];
  if (build.pkg) {
    const company = build.pkg.pages.find((p) => p.role === null)!;
    out.push("", "## Company page", "", `\`${company.slug}\` · advice **${company.advice.indexing}**: ${company.advice.reason}`, "", `Official sources: ${company.guide.official.length ? company.guide.official.map((o) => `[${o.title}](${o.url})`).join(", ") : "none recorded"}.`);
  }
  const skipped = build.roles.flatMap((r) => r.skipped);
  if (skipped.length) out.push("", "## Rounds left out of their role's page", "", table(["Role", "Round", "Accounts", "Why"], skipped.map((s) => [s.role, s.round, String(s.accounts), s.reason])));
  if (build.unresolved.length) {
    out.push("", "## Questions whose round could not be determined", "", "Kept in evidence.json, never imported.", "", table(["Experience", "Role", "Source's label", "Question"], build.unresolved.map((u) => [u.experience, u.role, u.round, u.text])));
  }
  if (build.issues.length) out.push("", "## Notes for the reviewer", "", ...build.issues.map((i) => `- ${i}`));
  return `${out.join("\n")}\n`;
}
